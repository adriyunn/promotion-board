// Writes docs/sw.js with the list of files to cache and a content-hash version.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const DOCS = path.join(__dirname, '..', 'docs');
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
const files = walk(DOCS).map((f) => path.relative(DOCS, f).split(path.sep).join('/'))
  .filter((f) => !f.startsWith('superpowers/') && !['sw.js', '.nojekyll'].includes(f)).sort();
const hash = crypto.createHash('sha1');
files.forEach((f) => hash.update(f).update(fs.readFileSync(path.join(DOCS, f))));
const version = hash.digest('hex').slice(0, 10);
const assets = ['./', ...files];
fs.writeFileSync(path.join(DOCS, 'sw.js'), `// Generated by app/build-sw.js. Cache-first, so the app works offline after the first visit.
const CACHE = 'steadfast-${version}';
const ASSETS = ${JSON.stringify(assets, null, 1)};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request).then((res) => {
    if (res.ok && new URL(e.request.url).origin === location.origin) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); }
    return res;
  })));
});
`);
console.log(`sw.js: ${assets.length} assets, cache steadfast-${version}`);
